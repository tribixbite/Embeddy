/**
 * Regenerate src/html-entities-table.ts from the WHATWG named character
 * reference list (https://html.spec.whatwg.org/entities.json).
 *
 * Only the semicolon-terminated names are kept: the legacy forms without a
 * semicolon (&amp, &copy …) are not decoded in attribute values when followed
 * by an alphanumeric or "=", which is exactly where the inspector reads
 * them, so decodeHtmlEntities requires the semicolon throughout.
 *
 * Usage: bun scripts/generate-html-entities.ts
 */
import { writeFileSync } from "node:fs";

const SOURCE = "https://html.spec.whatwg.org/entities.json";

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} → HTTP ${res.status}`);
const table = (await res.json()) as Record<string, { codepoints: number[]; characters: string }>;

/** Non-printing and non-ASCII characters as \u escapes so the file stays readable */
const literal = (text: string) =>
  `"${[...text]
    .map((ch) => {
      const cp = ch.codePointAt(0)!;
      if (ch === '"' || ch === "\\") return `\\${ch}`;
      if (cp >= 0x20 && cp < 0x7f) return ch;
      return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, "0")}`;
    })
    .join("")}"`;

const entries = Object.entries(table)
  .filter(([name]) => name.endsWith(";"))
  .map(([name, { characters }]) => [name.slice(1, -1), characters] as const)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const body = entries.map(([name, chars]) => `  ${name}: ${literal(chars)},`).join("\n");
const out = `/**
 * WHATWG named character references (semicolon forms), generated by
 * scripts/generate-html-entities.ts from ${SOURCE}.
 * ${entries.length} names. Do not edit by hand.
 */
export const NAMED_REFERENCES: Readonly<Record<string, string>> = {
${body}
};
`;
writeFileSync(new URL("../src/html-entities-table.ts", import.meta.url), out);
console.log(`wrote ${entries.length} names`);
