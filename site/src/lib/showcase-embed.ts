/**
 * The component embed for embeddy.link/showcase — a link that, pasted into
 * Discord, uses every documented limit of a component embed at once:
 *
 *   3,000 bytes   the payload is exactly 3,000 bytes for https://embeddy.link/
 *   40 components the Container plus 39 children, exactly
 *   10 media      a full Media Gallery: 9 animated WebPs and one MP4 with sound
 *
 * and every component type a component embed allows (Container, Section,
 * Text Display, Thumbnail, Media Gallery, Separator, Action Row, link
 * Button), with the parts Discord renders specially: spoilered media, a
 * disabled button, emoji buttons, an ANSI-coloured code block, headings,
 * subtext, quotes, lists, spoiler text, masked links and a live timestamp.
 *
 * Media is generated by scripts/generate-showcase-media.sh into
 * site/public/s/ — short paths, because every URL byte counts.
 */

import { serializeComponentEmbed } from "./inspect/component-embed";
import type { ButtonComponent, ContainerComponent } from "./inspect/component-embed";

/** Hot pink accent strip */
export const SHOWCASE_ACCENT = 0xff3d9a;

/**
 * The gallery in display order; 0 is the full-width hero tile, 9 the video.
 * Only `alt` goes into the payload — alt text on all ten would cost ~250 of
 * the 3,000 bytes, so it is kept for the hero and the video tile.
 */
export const SHOWCASE_MEDIA: ReadonlyArray<{ file: string; title: string; alt?: string }> = [
  { file: "0.webp", title: "Mandelbrot zoom", alt: "Mandelbrot zoom" },
  { file: "1.webp", title: "Game of Life" },
  { file: "2.webp", title: "Rule 30" },
  { file: "3.webp", title: "Metaballs" },
  { file: "4.webp", title: "Plasma" },
  { file: "5.webp", title: "Tunnel" },
  { file: "6.webp", title: "Lissajous" },
  { file: "7.webp", title: "Zone plate" },
  { file: "8.webp", title: "Sierpinski" },
  { file: "9.mp4", title: "Arpeggio", alt: "Video with sound" },
];

/** Thumbnail used by the Section accessories */
export const SHOWCASE_THUMB = "t.webp";

/** ANSI SGR escape as Discord's ```ansi blocks read it */
const esc = (codes: string) => `\u001b[${codes}m`;

export interface ShowcaseInput {
  /** Site origin with trailing slash, e.g. https://embeddy.link/ */
  siteUrl: string;
  /** Unix seconds shown as a live relative timestamp (build time) */
  builtAt: number;
}

/** Build the payload object */
export function buildShowcaseEmbed(input: ShowcaseInput): { component: ContainerComponent } {
  const site = input.siteUrl.endsWith("/") ? input.siteUrl : `${input.siteUrl}/`;
  const media = (file: string) => ({ url: `${site}s/${file}` });
  const button = (label: string, path: string, emoji?: string, disabled?: boolean): ButtonComponent => ({
    type: 2,
    style: 5,
    url: `${site}${path}`,
    ...(label ? { label } : {}),
    ...(emoji ? { emoji: { name: emoji } } : {}),
    ...(disabled ? { disabled: true } : {}),
  });

  // The three limits, each number in its own ANSI colour
  const ansi =
    "```ansi\n" +
    `${esc("1;35")}3000${esc("0")} bytes ${esc("1;34")}40${esc("0")} parts ${esc("1;36")}10${esc("0")} media\n` +
    "```";

  return {
    component: {
      type: 17,
      accent_color: SHOWCASE_ACCENT,
      components: [
        {
          type: 9,
          components: [
            { type: 10, content: "# ✨ Embeddy Showcase" },
            { type: 10, content: "### One link. Every limit." },
            { type: 10, content: "-# component embed · no bot, just HTML" },
          ],
          accessory: { type: 11, media: media(SHOWCASE_THUMB) },
        },
        { type: 14 },
        { type: 10, content: "-# 9 animated WebPs + 1 MP4 · tap ▶ for sound" },
        { type: 12, items: SHOWCASE_MEDIA.map((m) => ({ media: media(m.file), ...(m.alt ? { description: m.alt } : {}) })) },
        { type: 10, content: ansi },
        { type: 14, divider: true, spacing: 2 },
        { type: 10, content: "### Markdown" },
        {
          type: 9,
          components: [{ type: 10, content: "Tiles are **animated WebP** *made* __with__ ~~magic~~ `ffmpeg` ||and love||" }],
          accessory: button("Convert", "tools/convert/", "🎞️"),
        },
        {
          type: 9,
          components: [
            { type: 10, content: `> Built <t:${input.builtAt}:R>` },
            { type: 10, content: "-# live, in *your* timezone" },
          ],
          accessory: { type: 11, media: media(SHOWCASE_THUMB), spoiler: true },
        },
        { type: 10, content: "1. Paste the link\n2. Discord reads the JSON\n3. from `<head>`" },
        { type: 14 },
        { type: 10, content: "### Link buttons" },
        { type: 14 },
        {
          type: 1,
          components: [
            button("", "tools/convert/", "🎞️"),
            button("", "tools/squoosh/", "🗜️"),
            button("", "tools/inspect/", "🔍"),
            button("", "tools/upload/", "☁️"),
            button("", "showcase/", "✨"),
          ],
        },
        {
          // The limits as disabled buttons — Discord greys them out
          type: 1,
          components: [
            button("3000", "", "📦", true),
            button("40", "", "🧩", true),
            button("10", "", "🖼️", true),
            button("", "", "🏠"),
          ],
        },
        { type: 14 },
        {
          type: 9,
          components: [
            { type: 10, content: "## Build your own" },
            { type: 10, content: "-# live preview + validator" },
          ],
          accessory: button("Inspect", "tools/inspect/", "🔍"),
        },
        { type: 10, content: "-# embeddy.link ✨" },
      ],
    },
  };
}

/** The payload as minified JSON, safe to place inside the <script> element */
export function showcaseEmbedJson(input: ShowcaseInput): string {
  return serializeComponentEmbed(buildShowcaseEmbed(input));
}
